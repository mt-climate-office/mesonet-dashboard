#!/usr/bin/env node
/**
 * Mesonet API contract smoke test (+ allowlist generator).
 *
 *   node scripts/api-contract-smoke.mjs                 # verify + live requests
 *   node scripts/api-contract-smoke.mjs --no-requests   # spec checks only
 *   node scripts/api-contract-smoke.mjs --emit-allowlist  # (re)write src/lib/api/paramAllowlist.ts
 *
 * Verify mode re-fetches the OpenAPI spec and checks that:
 *  1. every endpoint pattern the app calls (USED below) exists in the spec,
 *     or is an explicitly declared hidden route;
 *  2. each representative request only uses query params the spec (or the
 *     hidden-route entry) allows — the class of bug `premade` was;
 *  3. the committed `paramAllowlist.ts` matches the live spec;
 *  4. one representative GET per pattern returns 200 (sequential, polite).
 * Exits non-zero on any failure.
 *
 * Env: MESONET_API (default https://mesonet2.climate.umt.edu/api/v2/),
 *      MESONET_SPEC (default https://mesonet2.climate.umt.edu/api/openapi.json).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const API = (process.env.MESONET_API ?? 'https://mesonet2.climate.umt.edu/api/v2/').replace(/\/?$/, '/')
const SPEC = process.env.MESONET_SPEC ?? 'https://mesonet2.climate.umt.edu/api/openapi.json'
const here = dirname(fileURLToPath(import.meta.url))
const ALLOWLIST_TS = join(here, '../src/lib/api/paramAllowlist.ts')

/**
 * Routes the API serves but leaves out of the OpenAPI document. Keep this the
 * single source of truth: --emit-allowlist copies it into paramAllowlist.ts.
 */
const HIDDEN = {
  '/derived/swp/': {
    params: ['stations', 'type'],
    note: 'Lab retention points (station, Depth [cm], KPA, VWC) for SWP clipping.',
  },
}

/* Ag/Latest/Downloader call sites (photos come from the data2 archive, not the API), with a light representative request. */
const d = (n) => new Date(Date.now() - n * 864e5).toISOString().slice(0, 10)
const USED = [
  ['/stations/', { type: 'csv' }],
  ['/elements/', { type: 'csv' }],
  ['/elements/{station}/', { type: 'csv' }, { station: 'acebozem' }],
  ['/latest/', { stations: 'acebozem', type: 'csv' }],
  ['/config/{station}/', {}, { station: 'acebozem' }],
  ['/derived/ppt/', { stations: 'acebozem', type: 'csv' }],
  ['/observations/', { stations: 'acebozem', elements: 'air_temp', start_time: d(2), end_time: d(1), level: 1, rm_na: true, public: true, type: 'csv' }],
  ['/observations/hourly/', { stations: 'acebozem', elements: 'air_temp,rh,sol_rad,wind_spd', agg_func: 'avg', start_time: d(2), end_time: d(1), level: 2, type: 'csv' }],
  ['/observations/daily/', { stations: 'acebozem', elements: 'air_temp,air_temp,air_temp,rh,rh,rh,sol_rad,wind_spd', agg_func: 'min,max,avg,min,max,avg,avg,avg', start_time: d(4), end_time: d(1), level: 2, type: 'csv' }],
  ['/derived/hourly/', { stations: 'acebozem', elements: 'etr', start_time: d(2), end_time: d(1), level: 1, rm_na: true, na_info: false, alpha: 0.23, type: 'csv' }],
  ['/derived/daily/', { stations: 'acebozem', elements: 'gdd', crop: 'wheat', keep: true, start_time: d(4), end_time: d(1), level: 2, type: 'csv' }],
  ['/derived/swp/', { stations: 'acebozem', type: 'csv' }],
]

const args = new Set(process.argv.slice(2))

async function getSpec() {
  const r = await fetch(SPEC)
  if (!r.ok) throw new Error(`spec ${SPEC}: HTTP ${r.status}`)
  return r.json()
}

/** { '/observations/daily/': ['agg_func', …] } from the spec (GET only). */
function specParams(spec) {
  const out = {}
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    const op = item.get
    if (!op) continue
    const shared = item.parameters ?? []
    const names = [...shared, ...(op.parameters ?? [])]
      .filter((p) => p.in === 'query')
      .map((p) => p.name)
    out[path] = [...new Set(names)].sort()
  }
  return out
}

function renderAllowlist(params) {
  const lines = [
    '/**',
    ' * GENERATED by `npm run gen:api` (scripts/api-contract-smoke.mjs --emit-allowlist)',
    ' * from https://mesonet2.climate.umt.edu/api/openapi.json. Do not edit by hand;',
    ' * add hidden routes to HIDDEN in that script instead.',
    ' *',
    ' * Per-endpoint GET query-parameter allowlist enforced by `lib/api/http.ts`.',
    ' * Keys are OpenAPI path templates (leading + trailing slash).',
    ' */',
    '',
    'export const SPEC_PARAM_ALLOWLIST: Readonly<Record<string, readonly string[]>> = {',
  ]
  for (const p of Object.keys(params).sort()) {
    lines.push(`  '${p}': [${params[p].map((n) => `'${n}'`).join(', ')}],`)
  }
  lines.push('}', '')
  lines.push('/** Routes the API serves but omits from the spec. */')
  lines.push('export const HIDDEN_PARAM_ALLOWLIST: Readonly<Record<string, readonly string[]>> = {')
  for (const [p, h] of Object.entries(HIDDEN)) {
    lines.push(`  // ${h.note}`)
    lines.push(`  '${p}': [${h.params.map((n) => `'${n}'`).join(', ')}],`)
  }
  lines.push('}', '')
  lines.push('export const PARAM_ALLOWLIST: Readonly<Record<string, readonly string[]>> = {')
  lines.push('  ...SPEC_PARAM_ALLOWLIST,')
  lines.push('  ...HIDDEN_PARAM_ALLOWLIST,')
  lines.push('}', '')
  return lines.join('\n')
}

function fillPath(template, vars = {}) {
  return template.replace(/\{(\w+)\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`missing path var ${k} for ${template}`)
    return encodeURIComponent(vars[k])
  })
}

const qs = (q) =>
  Object.entries(q)
    .map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v)).replace(/%2C/g, ',')}`)
    .join('&')

async function main() {
  const spec = await getSpec()
  const params = specParams(spec)

  if (args.has('--emit-allowlist')) {
    writeFileSync(ALLOWLIST_TS, renderAllowlist(params))
    console.log(`wrote ${ALLOWLIST_TS} (${Object.keys(params).length} spec + ${Object.keys(HIDDEN).length} hidden routes)`)
    return
  }

  const failures = []
  const allow = { ...params, ...Object.fromEntries(Object.entries(HIDDEN).map(([k, v]) => [k, v.params])) }

  // 3. committed allowlist in sync with the live spec
  try {
    const committed = readFileSync(ALLOWLIST_TS, 'utf8')
    if (committed !== renderAllowlist(params)) {
      failures.push('paramAllowlist.ts is out of date with the live spec — run `npm run gen:api`')
    }
  } catch (e) {
    failures.push(`cannot read ${ALLOWLIST_TS}: ${e.message}`)
  }

  for (const [pattern, query, vars] of USED) {
    // 1. pattern exists
    const inSpec = pattern in params
    const hidden = pattern in HIDDEN
    if (!inSpec && !hidden) {
      failures.push(`${pattern}: not in the OpenAPI spec and not declared hidden`)
      continue
    }
    if (inSpec && hidden) {
      console.warn(`note: ${pattern} is now in the spec; remove it from HIDDEN`)
    }
    // 2. params allowed
    const bad = Object.keys(query).filter((k) => !allow[pattern].includes(k))
    if (bad.length) failures.push(`${pattern}: params not allowed by spec: ${bad.join(', ')}`)

    // 4. live request
    if (args.has('--no-requests')) continue
    const url = `${API}${fillPath(pattern, vars).replace(/^\//, '')}${Object.keys(query).length ? `?${qs(query)}` : ''}`
    const t0 = Date.now()
    try {
      const ctrl = new AbortController()
      const timer = setTimeout(() => ctrl.abort(), 90_000)
      const r = await fetch(url, { signal: ctrl.signal })
      clearTimeout(timer)
      await r.arrayBuffer()
      const ms = Date.now() - t0
      if (r.status !== 200) failures.push(`${pattern}: HTTP ${r.status} on ${url}`)
      console.log(`${r.status === 200 ? 'ok ' : 'ERR'} ${r.status} ${String(ms).padStart(6)} ms  ${pattern}`)
    } catch (e) {
      failures.push(`${pattern}: ${e.name === 'AbortError' ? 'timeout' : e.message} on ${url}`)
      console.log(`ERR  --- ${String(Date.now() - t0).padStart(6)} ms  ${pattern}`)
    }
  }

  if (failures.length) {
    console.error(`\n${failures.length} contract failure(s):`)
    for (const f of failures) console.error(`  - ${f}`)
    process.exit(1)
  }
  console.log(`\nAPI contract OK (${USED.length} endpoint patterns).`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
